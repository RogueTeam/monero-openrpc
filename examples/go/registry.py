#!/usr/bin/env python3
"""Write registry_test.go: maps schema titles to the generated Go types, for the tests.
Usage: registry.py PACKAGE types.go > PACKAGE/registry_test.go"""
import re
import sys

pkg, path = sys.argv[1], sys.argv[2]
names = sorted(set(re.findall(r"^type (\w+) (?:struct|map)", open(path).read(), re.M)))
cases = "\n".join(f'\tcase "{n.lower()}":\n\t\treturn new({n})' for n in names)
print(f"""// Code generated by registry.py. DO NOT EDIT.

package {pkg}

import "strings"

// newOf returns a new value of the generated type for a schema title. Titles are
// matched case-insensitively because quicktype re-cases some names (MakeUri -> MakeURI).
func newOf(title string) interface{{}} {{
	switch strings.ToLower(title) {{
{cases}
	}}
	return nil
}}""")
