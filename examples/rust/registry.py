#!/usr/bin/env python3
"""Write tests/registry/mod.rs: maps schema titles to the generated Rust types, for the tests.
Usage: registry.py src/monerod.rs src/walletrpc.rs > tests/registry/mod.rs"""
import re
import sys
from pathlib import Path

out = ["""// Code generated by registry.py. DO NOT EDIT.

use serde::{de::DeserializeOwned, Serialize};
use serde_json::Value;

/// Decodes a JSON value into T and encodes it back.
fn roundtrip<T: DeserializeOwned + Serialize>(v: &Value) -> Result<Value, serde_json::Error> {
    let t: T = serde_json::from_value(v.clone())?;
    serde_json::to_value(&t)
}

/// What a generated type does with an example: the re-encoded value (or the decode
/// error), and whether the type is a map (quicktype's choice for empty-object schemas).
pub struct Outcome {
    pub result: Result<Value, serde_json::Error>,
    pub is_map: bool,
}
"""]
for path in sys.argv[1:]:
    module = Path(path).stem
    src = open(path).read()
    structs = set(re.findall(r"^pub struct (\w+)", src, re.M))
    maps = set(re.findall(r"^pub type (\w+) = HashMap<", src, re.M))
    arms = "\n".join(
        f'        "{n.lower()}" => roundtrip::<{module}::{n}>(v),' for n in sorted(structs | maps))
    map_names = ", ".join(f'"{n.lower()}"' for n in sorted(maps))
    out.append(f"""
/// Runs a {module} example through the type for a schema title. Titles are matched
/// case-insensitively because quicktype re-cases some names (MakeUri -> MakeURI).
pub fn {module}(title: &str, v: &Value) -> Option<Outcome> {{
    use monero_rpc_examples::{module};
    let title = title.to_lowercase();
    let result = match title.as_str() {{
{arms}
        _ => return None,
    }};
    Some(Outcome {{ result, is_map: [{map_names}].contains(&title.as_str()) }})
}}
""")
print("".join(out), end="")
